/** 문서 시행일. 내용을 바꾸면 이 날짜와 CHANGELOG 를 함께 고친다. */
export const POLICY_DATE = '2026년 11월 10일'
const TBD = '정식 운영 전 정해질 예정이에요'

function useOperator() {
  const [op, setOp] = useState<Operator | null>(null)
  useEffect(() => {
    siteConfig().then((c) => setOp(c.operator))
  }, [])
  return op
}

function Doc({ eyebrow, title, sections }: { eyebrow: string; title: string; sections: [string, ReactNode][] }) {
  const op = useOperator()
  return (
    <article className="container page legal">
      <header className="page-head">
        <div>
          <p className="eyebrow en">{eyebrow}</p>
          <h1 className="page-title">{title}</h1>
          <p className="muted small">시행일 {POLICY_DATE}</p>
        </div>
      </header>
      {/* 운영 기관 · 문의처를 아직 정하지 않았을 때만 */}
      {!(op?.name && op?.contact) && <p className="demo-note">운영 기관 · 문의처가 아직 정해지지 않았어요. 운영자는 서비스를 열기 전에 관리자 화면 ‘사이트 설정’에서 정해 주세요.</p>}
      <nav className="legal-toc card" aria-label="목차">
        <ol>
          {sections.map(([h], i) => (
            <li key={h}>
              {/* 목록 번호(ol)가 붙으니 제목 앞의 ‘1.’ · ‘제1조’는 빼고 보여준다 */}
              <a href={`#s${i + 1}`}>{h.replace(/^(\d+\.|제\d+조)\s*/, '')}</a>
            </li>
          ))}
        </ol>
      </nav>
      {sections.map(([h, body], i) => (
        <section key={h} id={`s${i + 1}`} className="legal-section">
          <h2>{h}</h2>
          {body}
        </section>
      ))}
      <p className="muted small center legal-foot">
        <Link to="/terms">이용약관</Link> · <Link to="/privacy">개인정보 처리방침</Link>
      </p>
    </article>
  )
}

